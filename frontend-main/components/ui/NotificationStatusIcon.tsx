type NotificationTone = "pending" | "error" | "success";

const ERROR_KEYWORDS = [
  "ยกเลิก",
  "ถูกยกเลิก",
  "ตีกลับ",
  "ไม่ผ่าน",
  "abort",
  "cancel",
  "reject",
  "failed",
  "invalid",
];

const SUCCESS_KEYWORDS = [
  "เสร็จสมบูรณ์",
  "เสร็จสิ้น",
  "เรียบร้อย",
  "ผ่าน",
  "ตอบรับ",
  "complete",
  "completed",
  "success",
  "approved",
  "verified",
];

const PENDING_KEYWORDS = [
  "รอ",
  "ตรวจสอบ",
  "สัมภาษณ์",
  "ดำเนินการ",
  "pending",
  "review",
  "waiting",
  "new",
];

export function detectNotificationTone(title: string, message: string): NotificationTone {
  const text = `${title} ${message}`.toLowerCase();

  if (ERROR_KEYWORDS.some((keyword) => text.includes(keyword.toLowerCase()))) {
    return "error";
  }

  if (SUCCESS_KEYWORDS.some((keyword) => text.includes(keyword.toLowerCase()))) {
    return "success";
  }

  if (PENDING_KEYWORDS.some((keyword) => text.includes(keyword.toLowerCase()))) {
    return "pending";
  }

  return "pending";
}

